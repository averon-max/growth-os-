// Rebuilds src/app/blog/posts.ts from every src/app/blog/<slug>/meta.ts. Run after adding or removing a post.
import fs from "node:fs";
import path from "node:path";
const dir = path.join(process.cwd(), "src/app/blog");
const slugs = fs.readdirSync(dir).filter((d) => /^[a-z0-9-]+$/.test(d) && fs.existsSync(path.join(dir, d, "meta.ts"))).sort();
const name = (s) => "p_" + s.replace(/-/g, "_");
const out = `import type { PostInfo } from "@/lib/blog-meta";\n${slugs.map((s) => `import { post as ${name(s)} } from "./${s}/meta";`).join("\n")}\n\n// Generated by scripts/sync-posts.mjs — do not edit by hand.\nexport const CODE_POSTS: PostInfo[] = [${slugs.map(name).join(", ")}];\n`;
fs.writeFileSync(path.join(dir, "posts.ts"), out);
console.log(`posts.ts: ${slugs.length} post(s)${slugs.length ? " — " + slugs.join(", ") : ""}`);
